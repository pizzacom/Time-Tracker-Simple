let currentLang = 'de';

export function setLanguage(lang) {
    currentLang = lang;
    localStorage.setItem('zeittracker_language', lang);
}

export function getLanguage() {
    return currentLang;
}

export function loadLanguage() {
    currentLang = localStorage.getItem('zeittracker_language') || 'de';
    return currentLang;
}

export function t(key) {
    return translations[currentLang]?.[key] || translations.de?.[key] || key;
}

export function getMonthName(date) {
    return t('months')[date.getMonth()];
}

export function updateDOMTranslations() {
    document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        const val = t(key);
        if (val !== key) {
            // For <option> or elements with child nodes that should keep children, set textContent
            // For <select> option elements, use textContent to translate
            el.textContent = val;
        }
    });
    document.querySelectorAll('[data-i18n-placeholder]').forEach(el => {
        const key = el.getAttribute('data-i18n-placeholder');
        const val = t(key);
        if (val !== key) el.placeholder = val;
    });
    document.querySelectorAll('[data-i18n-title]').forEach(el => {
        const key = el.getAttribute('data-i18n-title');
        const val = t(key);
        if (val !== key) el.title = val;
    });
}
